export function getFeatureMessages(language: LanguageCode): FeatureMessages {
  return language === "ru" ? RU : EN;
}

/** `text` with `{name}` replaced. */
export function fill(text: string, values: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
}

/** Words for a key of the loot and places tables (falls back to the key). */
export function featureText(messages: FeatureMessages, key: string): string {
  return (messages as Record<string, string>)[key] ?? key;
}
