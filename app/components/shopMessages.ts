export function getShopMessages(language: LanguageCode): ShopMessages {
  return language === "ru" ? RU : EN;
}

/** A word from the table by key (decor ids, find kinds), or the key itself. */
export function shopText(messages: ShopMessages, key: string): string {
  return (messages as Record<string, string>)[key] ?? key;
}

/** The name of a find kind. */
export function findName(messages: ShopMessages, kind: string): string {
  return shopText(messages, `find_${kind}`);
}
