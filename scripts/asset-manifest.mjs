#!/usr/bin/env node
/**
 * Writes `src/simulator/core/assetManifest.ts`: a content hash and the size
 * of every model, texture and sound under `public/`.
 *
 *   node scripts/asset-manifest.mjs
 *
 * The game asks for `/models/x.glb?v=<hash>` (`assetUrl`): the URL changes
 * exactly when the file does, so browsers, the CDN and the service worker
 * may keep it forever and never ask the server again; and the sizes let the
 * loading bar move with the bytes that have arrived. Run it after changing
 * any of these files (a unit test fails while the manifest is stale).
 */
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const PUBLIC = path.join(ROOT, "public");
const FOLDERS = ["models", "textures", "audio"];
const TYPES = /\.(?:glb|webp|jpe?g|png|mp3|ogg)$/i;

export function listAssets() {
  const out = [];
  const walk = (directory) => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const full = path.join(directory, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (TYPES.test(entry.name)) out.push(full);
    }
  };
  for (const folder of FOLDERS) walk(path.join(PUBLIC, folder));
  return out.map((file) => {
    const data = fs.readFileSync(file);
    return { url: `/${path.relative(PUBLIC, file).split(path.sep).join("/")}`, v: createHash("sha256").update(data).digest("hex").slice(0, 10), bytes: data.length };
  });
}

export function manifestSource(assets) {
  const lines = assets.map((asset) => `  ${JSON.stringify(asset.url)}: { v: ${JSON.stringify(asset.v)}, bytes: ${asset.bytes} },`);
  return `// Generated by scripts/asset-manifest.mjs — do not edit; run \`node scripts/asset-manifest.mjs\` after changing a file under public/models, textures or audio.

/** Content hash (for the URL) and size (for the loading bar) of every model, texture and sound. */
export const ASSET_MANIFEST: Readonly<Record<string, { v: string; bytes: number }>> = {
${lines.join("\n")}
};

/**
 * The URL to fetch \`path\` from: with its content hash, so a cached copy is
 * never stale and never needs revalidating (a new file is a new URL).
 */
export function assetUrl(path: string): string {
  const entry = ASSET_MANIFEST[path];
  return entry ? \`\${path}?v=\${entry.v}\` : path;
}

/** The size of \`path\` in bytes (an estimate of 1 MB for a file not listed). */
export function assetBytes(path: string): number {
  return ASSET_MANIFEST[path]?.bytes ?? 1_000_000;
}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const target = path.join(ROOT, "src/simulator/core/assetManifest.ts");
  const assets = listAssets();
  fs.writeFileSync(target, manifestSource(assets));
  console.log(`${path.relative(ROOT, target)}: ${assets.length} files, ${(assets.reduce((sum, asset) => sum + asset.bytes, 0) / 1e6).toFixed(1)} MB`);
}
