/** The words without their punctuation and case (ё read as е): what a recording is matched by. */
export function voiceKey(text: string): string {
  return text
    .toLowerCase()
    .replace(/ё/gu, "е")
    .replace(/[^a-zа-я0-9]+/gu, " ")
    .trim();
}

/** The recording of these words, if there is one. */
export function voiceFor(text: string): { clip: string; seconds: number } | null {
  const clip = VOICE_BY_WORDS[voiceKey(text)];
  return clip ? { clip, seconds: VOICE_SECONDS[clip] ?? 0 } : null;
}
